#!/usr/bin/env python3
"""tools/nitric_pytest.py — run custom_Database's tests INSIDE `nitric start`.

Adapted from GAN_ecc's harness/nitric_pytest.py: declaring a Nitric resource
connects to the server at import, and `nitric start` gives each service its own
port, so pytest runs as a Nitric service; one process per test, 60s limit each.

    python tools/nitric_pytest.py          (from the repo root; Docker Desktop must be running)

ORIGINAL DOC (GAN_ecc):

    cd <run-dir> && python nitric_pytest.py --run-dir .     (run.sh and drill.sh do this)

Why: under the Nitric profile, code that declares a resource connects to the
Nitric server when it is imported, and `nitric start` gives each service its
own port in SERVICE_ADDRESS. So pytest runs as a Nitric service (proven by
harness/spikes/nitric-pytest on Andrew's Windows machine, 2026-10-23).

It reads <run-dir>/impl and <run-dir>/tests, and writes <run-dir>/report.xml,
exactly as the plain pytest call does. Only specs that list resources are
graded this way (ifc_check.py --runner); a "none" spec stays plain pytest.

Exit 0: pytest ran (pass or fail; report.xml decides). Exit 3: it could not
run (no Docker engine, no Nitric CLI, no Python 3.11-3.13, timeout). It never
runs `nitric up`.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import signal
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
VENV = HERE / ".venv-nitric"
SDK_PIN = "nitric==1.2.4"
WIN = os.name == "nt"
BOOTSTRAP = '''"""Generated by harness/nitric_pytest.py. Runs grade_impl.py, and writes done.json
even if the grader itself cannot start, so the runner never waits for nothing."""
import json, runpy, traceback
from pathlib import Path
HERE = Path(__file__).resolve().parent.parent
try:
    runpy.run_path(str(HERE / "grade_impl.py"), run_name="__main__")
except BaseException:
    if not (HERE / "done.json").exists():
        (HERE / "done.json").write_text(json.dumps({"error": traceback.format_exc()}))
'''

SERVICE = '''"""Generated by harness/nitric_pytest.py: runs the round's tests inside nitric start.

Each test runs in its OWN process with a time limit, so one hanging test
(for example an exponentially large value) is reported as that test failing
instead of freezing the whole round with no report. Python cannot interrupt
a long call from another thread, but it can always kill a process.
"""
import json, os, subprocess, sys, tempfile, time, traceback
import xml.etree.ElementTree as ET
from pathlib import Path
RUN = Path(r"__RUN__")
LIMIT = float(os.environ.get("NITRIC_TEST_TIMEOUT", "60"))
env = dict(os.environ, PYTHONPATH=str(RUN) + os.pathsep + os.environ.get("PYTHONPATH", ""))
res = {"service_address": os.environ.get("SERVICE_ADDRESS"), "per_test_limit_s": LIMIT, "timed_out": []}
base = [sys.executable, "-m", "pytest", "-p", "no:cacheprovider", "-q"]
try:
    col = subprocess.run(base + ["--collect-only", str(RUN / "tests")], cwd=RUN, env=env,
                         capture_output=True, text=True, timeout=300)
    ids = [l.strip() for l in col.stdout.splitlines() if "::" in l and not l.startswith(("=", " "))]
    if col.returncode != 0 or not ids:
        # collection failed (e.g. an import error): one plain run, so the report shows why
        r = subprocess.run(base + [str(RUN / "tests"), "--junit-xml=" + str(RUN / "report.xml")],
                           cwd=RUN, env=env, capture_output=True, text=True, timeout=600)
        print(r.stdout[-4000:]); res["pytest_exit"] = r.returncode
    else:
        cases, tmp = [], Path(tempfile.mkdtemp(prefix="grade-"))
        for n, tid in enumerate(ids):
            xml = tmp / f"{n}.xml"; t0 = time.time()
            try:
                r = subprocess.run(base + [tid, "--junit-xml=" + str(xml)], cwd=RUN, env=env,
                                   capture_output=True, text=True, timeout=LIMIT)
                print("." if r.returncode == 0 else "F", end="", flush=True)
                cases += list(ET.parse(xml).getroot().iter("testcase")) if xml.exists() else []
            except subprocess.TimeoutExpired:
                print("T", end="", flush=True)
                res["timed_out"].append(tid)
                mod, _, name = tid.partition("::")
                tc = ET.Element("testcase", classname=mod.replace("/", ".").removesuffix(".py"), name=name,
                                time=f"{time.time() - t0:.1f}")
                f = ET.SubElement(tc, "failure", message=f"timed out after {LIMIT:.0f}s: the test did not finish")
                f.text = f"{tid} was still running after {LIMIT:.0f}s and its process was killed."
                cases.append(tc)
        fails = sum(1 for c in cases if c.find("failure") is not None)
        errs = sum(1 for c in cases if c.find("error") is not None)
        skips = sum(1 for c in cases if c.find("skipped") is not None)
        suites = ET.Element("testsuites")
        suite = ET.SubElement(suites, "testsuite", name="pytest", tests=str(len(cases)), failures=str(fails),
                              errors=str(errs), skipped=str(skips))
        suite.extend(cases)
        ET.ElementTree(suites).write(RUN / "report.xml", encoding="utf-8", xml_declaration=True)
        print()
        print(f"{len(cases) - fails - errs - skips} passed, {fails} failed, {errs} errors, {skips} skipped"
              f"{', ' + str(len(res['timed_out'])) + ' timed out' if res['timed_out'] else ''} (one process per test)")
        res["pytest_exit"] = 0 if fails == errs == 0 else 1
except BaseException:
    res["error"] = traceback.format_exc()
(Path(__file__).resolve().parent / "done.json").write_text(json.dumps(res))
'''


def die(msg: str) -> None:
    print(f"NITRIC RUNNER: cannot grade — {msg}", file=sys.stderr)
    sys.exit(3)


def run(cmd, **kw):
    assert "up" not in cmd[1:2], "never `nitric up`"
    try:
        return subprocess.run(cmd, capture_output=True, text=True, **kw)
    except subprocess.TimeoutExpired as e:
        return subprocess.CompletedProcess(cmd, 124, "", f"timed out after {e.timeout:.0f}s")
    except OSError as e:
        return subprocess.CompletedProcess(cmd, 127, "", str(e))


def venv_python() -> Path:
    return VENV / ("Scripts/python.exe" if WIN else "bin/python")


def ensure_venv() -> Path:
    vp = venv_python()
    if vp.exists():
        return vp
    cands = ([["py", "-3.13"], ["py", "-3.12"], ["py", "-3.11"]] if WIN else []) + \
            [["python3.13"], ["python3.12"], ["python3.11"], [sys.executable], ["python3"], ["python"]]
    for c in cands:
        if not shutil.which(c[0]):
            continue
        r = run(c + ["-c", "import sys; print('%d.%d' % sys.version_info[:2])"], timeout=20)
        if r.returncode == 0 and r.stdout.strip() in ("3.11", "3.12", "3.13"):
            if run(c + ["-m", "venv", str(VENV)], timeout=180).returncode != 0:
                die(f"could not make {VENV}")
            r = run([str(vp), "-m", "pip", "install", "-q", "--disable-pip-version-check", SDK_PIN, "pytest"], timeout=900)
            if r.returncode != 0:
                die("pip install failed: " + r.stderr.strip()[-300:])
            return vp
    die("no Python 3.11-3.13 found (the Nitric SDK needs 3.11+, and 3.14 breaks its protobuf)")


PROJECT = "custom-database-tests"
CONTAINER = f"nitric-{PROJECT}-local-sql"   # named by the CLI: pkg/cloud/sql/sql.go


def remove_container(why: str) -> None:
    """Remove ONLY the grading project's own Postgres container, by exact name."""
    q = run(["docker", "ps", "-aq", "--filter", f"name=^/{CONTAINER}$"], timeout=60)
    if q.returncode == 0 and q.stdout.strip():
        r = run(["docker", "rm", "-f", CONTAINER], timeout=120)
        if r.returncode == 0:
            print(f"   [nitric runner] removed {CONTAINER} ({why})")
        elif "already in progress" not in r.stderr:      # that one is Docker finishing AutoRemove itself
            print(f"   [nitric runner] could not remove {CONTAINER}: {r.stderr.strip()[-200:]}")


def stop(proc) -> None:
    """Interrupt first: `nitric start` then stops its Postgres container, which
    removes itself (AutoRemove). A hard kill skips that and leaves the container
    behind, so the next run collides with its name. Kill only as a last resort."""
    if proc.poll() is None:
        try:
            if WIN:
                os.kill(proc.pid, signal.CTRL_BREAK_EVENT)
            else:
                os.killpg(proc.pid, signal.SIGINT)
            proc.wait(30)
        except (OSError, subprocess.TimeoutExpired):
            pass
    if proc.poll() is None:
        if WIN:
            subprocess.run(["taskkill", "/F", "/T", "/PID", str(proc.pid)], capture_output=True)
        else:
            try:
                os.killpg(proc.pid, signal.SIGKILL)
            except OSError:
                pass
    remove_container("left behind after nitric start stopped")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", default=str(HERE.parent))
    ap.add_argument("--timeout", type=int, default=int(os.environ.get("NITRIC_GRADE_TIMEOUT", "600")))
    a = ap.parse_args()
    rd = Path(a.run_dir).resolve()
    if not (rd / "custom_database").is_dir() or not (rd / "tests").is_dir():
        die(f"{rd} has no custom_database/ and tests/")
    nitric = shutil.which("nitric") or die("the Nitric CLI is not on PATH (see harness/spikes/nitric-pytest)")
    if not shutil.which("docker"):
        die("docker is not on PATH; nitric start needs Docker Desktop running")
    d = run(["docker", "info", "--format", "{{.ServerVersion}}"], timeout=60)
    if d.returncode != 0 or not d.stdout.strip():
        die("Docker's engine is not answering. Start Docker Desktop and wait for 'Engine running'.")
    vp = ensure_venv().as_posix()
    if " " in vp:
        die(f"the venv path has a space, which nitric's start command cannot take: {vp}")

    proj = rd / ".nitric-project"
    if proj.exists():
        shutil.rmtree(proj)
    (proj / "services").mkdir(parents=True)
    (proj / "services" / "grade.py").write_text(BOOTSTRAP, encoding="utf-8")
    (proj / "grade_impl.py").write_text(SERVICE.replace("__RUN__", str(rd)), encoding="utf-8")
    compile((proj / "grade_impl.py").read_text(encoding="utf-8"), "grade_impl.py", "exec")   # fail here, loudly, not in nitric
    remove_container("left over from an earlier run")
    (proj / "nitric.yaml").write_text(f"name: {PROJECT}\nservices:\n  - match: services/*.py\n    start: {vp} $SERVICE_PATH\n",
                                      encoding="utf-8")
    (rd / "report.xml").unlink(missing_ok=True)
    log_path = proj / "nitric-start.log"
    log = open(log_path, "w", encoding="utf-8", errors="replace")
    kw = {"creationflags": subprocess.CREATE_NEW_PROCESS_GROUP} if WIN else {"start_new_session": True}
    t0 = time.time()
    proc = subprocess.Popen([nitric, "start", "--no-browser"], cwd=proj, stdin=subprocess.DEVNULL,
                            stdout=log, stderr=subprocess.STDOUT, **kw)
    done = proj / "done.json"
    while time.time() - t0 < a.timeout and not done.exists() and proc.poll() is None:
        time.sleep(0.5)
    time.sleep(1)
    stop(proc); log.close()
    out = log_path.read_text(encoding="utf-8", errors="replace")
    # show the service's own pytest output, without the per-line service prefix
    shown = [l.split("]: ", 1)[1] if "]: " in l else l for l in out.splitlines()]
    print("\n".join(shown[-25:]))
    if not done.exists():
        die(f"no result from nitric start after {int(time.time() - t0)}s (exit {proc.returncode}); log: {log_path}")
    res = json.loads(done.read_text())
    if "error" in res:
        print(res["error"][-2000:], file=sys.stderr)
        die("pytest did not start inside nitric start")
    print(f"   [nitric runner] pytest ran inside nitric start at {res.get('service_address')} "
          f"in {int(time.time() - t0)}s; exit {res.get('pytest_exit')}")
    for tid in res.get("timed_out", []):
        print(f"   [nitric runner] TIMED OUT after {res.get('per_test_limit_s'):.0f}s: {tid}")
    sys.exit(0)


if __name__ == "__main__":
    main()
